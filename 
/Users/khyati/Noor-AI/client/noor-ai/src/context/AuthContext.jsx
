
import { createContext, useContext, useState, useCallback, useEffect } from "react";

const API_URL = import.meta.env.VITE_API_URL || "http://localhost:5000";

/**
 * AuthContext - Memory-only JWT Authentication
 * 
 * Stores token in React state (memory) only.
 * No cookies, no localStorage, no sessionStorage.
 * 
 * Works with origin = null (PDF/sandboxed iframes)
 */

const AuthContext = createContext(null);

export const AuthProvider = ({ children }) => {
  const [token, setToken] = useState(null);
  const [user, setUser] = useState(null);
  const [loading, setLoading] = useState(true);

  // Check for existing auth on mount
  useEffect(() => {
    // In sandboxed environments, no storage is available
    // Token must be provided via initialization or re-authentication
    setLoading(false);
  }, []);

  // Login function - stores token in memory only
  const login = useCallback(async (email, password) => {
    const response = await fetch(`${API_URL}/api/auth/login`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ email, password })
    });

    const data = await response.json();

    if (data.success && data.token) {
      setToken(data.token);
      setUser(data.user);
      return { success: true };
    }

    return { success: false, message: data.message };
  }, []);

  // Register function - stores token in memory only
  const register = useCallback(async (userData) => {
    const response = await fetch(`${API_URL}/api/auth/register`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(userData)
    });

    const data = await response.json();

    if (data.success && data.token) {
      setToken(data.token);
      setUser(data.user);
      return { success: true };
    }

    return { success: false, message: data.message };
  }, []);

  // Logout function - clears memory only
  const logout = useCallback(() => {
    setToken(null);
    setUser(null);
  }, []);

  // Get auth header for API calls
  const getAuthHeader = useCallback(() => {
    if (!token) return {};
    return { Authorization: `Bearer ${token}` };
  }, [token]);

  const value = {
    token,
    user,
    loading,
    isAuthenticated: !!token,
    login,
    register,
    logout,
    getAuthHeader
  };

  return (
    <AuthContext.Provider value={value}>
      {children}
    </AuthContext.Provider>
  );
};

export const useAuth = () => {
  const context = useContext(AuthContext);
  if (!context) {
    throw new Error("useAuth must be used within an AuthProvider");
  }
  return context;
};

export default AuthContext;

